from fpdf import FPDF

def export_pdf(required, filename):
    pdf = FPDF()
    pdf.add_page()
    
    # Header
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(26, 58, 108) # Navy Blue
    pdf.cell(0, 12, "NIRMAN - Official Approvals Checklist", ln=True, align='C')
    
    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 10, "Generated by Unified Approval & Compliance Management System", ln=True, align='C')
    pdf.ln(10)

    pdf.set_font("Helvetica", size=11)
    pdf.set_text_color(0, 0, 0)

    if not required:
        pdf.multi_cell(0, 8, "Based on your profile, no specific approvals are required at this stage.")
    else:
        for item in required:
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_fill_color(240, 240, 240)
            pdf.cell(0, 10, f" {item['approval']}", ln=True, fill=True)
            
            pdf.set_font("Helvetica", size=10)
            for doc in item["documents"]:
                pdf.cell(10) # indent
                pdf.cell(0, 8, f"[ ] {doc}", ln=True)
            pdf.ln(5)

    pdf.output(filename)
    return filename